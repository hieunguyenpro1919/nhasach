CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. CATEGORIES
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    icon TEXT DEFAULT '📚'
);

-- 2. APP USERS (Tách riêng để hỗ trợ đầy đủ role admin/seller/customer + id số tương thích)
CREATE TABLE IF NOT EXISTS public.app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_uid UUID UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT DEFAULT 'AUTH_MANAGED',
    role TEXT NOT NULL DEFAULT 'customer',
    phone TEXT DEFAULT '',
    gender TEXT DEFAULT '',
    dob TEXT DEFAULT '',
    address TEXT DEFAULT '',
    bio TEXT DEFAULT '',
    avatar TEXT DEFAULT '',
    "shopName" TEXT DEFAULT '',
    "shopDescription" TEXT DEFAULT '',
    "shopPhone" TEXT DEFAULT '',
    "shopAddress" TEXT DEFAULT '',
    "shopBio" TEXT DEFAULT '',
    "isLocked" BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'active',
    "shopStatus" TEXT NOT NULL DEFAULT 'active',
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. PRODUCTS
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC(12, 0) NOT NULL DEFAULT 0,
    image TEXT DEFAULT '',
    description TEXT DEFAULT '',
    author TEXT DEFAULT '',
    "categoryId" BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    tag TEXT DEFAULT '',
    "importDate" TIMESTAMPTZ DEFAULT NOW(),
    "soldCount" INTEGER NOT NULL DEFAULT 0,
    "onSale" BOOLEAN NOT NULL DEFAULT FALSE,
    "discountPercent" NUMERIC(5, 2) NOT NULL DEFAULT 0,
    "sellerId" BIGINT,
    "sellerName" TEXT DEFAULT '',
    status TEXT DEFAULT 'active',
    "isNew" BOOLEAN NOT NULL DEFAULT FALSE
);

-- 4. SALE CONFIG (Flash Sale toàn sàn)
CREATE TABLE IF NOT EXISTS public.sale_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "isActive" BOOLEAN NOT NULL DEFAULT FALSE,
    "campaignName" TEXT DEFAULT 'Flash Sale',
    "startTime" TIMESTAMPTZ,
    "endTime" TIMESTAMPTZ,
    "startDate" TEXT,
    "endDate" TEXT,
    "durationHours" NUMERIC(10, 4) DEFAULT 8,
    description TEXT DEFAULT ''
);

-- 5. COUPONS (Voucher)
CREATE TABLE IF NOT EXISTS public.coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    description TEXT DEFAULT '',
    "discountType" TEXT NOT NULL DEFAULT 'percent',
    "discountValue" NUMERIC(12, 2) NOT NULL DEFAULT 0,
    "maxDiscount" NUMERIC(12, 2) DEFAULT 0,
    "minOrderValue" NUMERIC(12, 2) DEFAULT 0,
    "usageLimit" INTEGER DEFAULT 0,
    "usedCount" INTEGER NOT NULL DEFAULT 0,
    "startsAt" TIMESTAMPTZ,
    "expiresAt" TIMESTAMPTZ,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. ORDERS
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "orderCode" TEXT NOT NULL,
    "userId" BIGINT,
    "userEmail" TEXT DEFAULT '',
    "receiverName" TEXT NOT NULL DEFAULT '',
    "receiverPhone" TEXT DEFAULT '',
    "receiverAddress" TEXT DEFAULT '',
    "receiverNote" TEXT DEFAULT '',
    "paymentMethod" TEXT DEFAULT 'cod',
    "paymentStatus" TEXT DEFAULT 'unpaid',
    "isPaid" BOOLEAN NOT NULL DEFAULT FALSE,
    "couponCode" TEXT DEFAULT '',
    "discountAmount" NUMERIC(12, 0) NOT NULL DEFAULT 0,
    "shippingFee" NUMERIC(12, 0) NOT NULL DEFAULT 0,
    "subTotal" NUMERIC(12, 0) NOT NULL DEFAULT 0,
    "totalAmount" NUMERIC(12, 0) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'Chờ xác nhận',
    "shippingCarrier" TEXT DEFAULT '',
    "trackingCode" TEXT DEFAULT '',
    "shippedAt" TIMESTAMPTZ,
