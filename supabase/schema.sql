-- Đồng bộ lại sequence ID sau khi seed dữ liệu có sẵn id từ db.json
CREATE OR REPLACE FUNCTION public.sync_table_sequences()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    tbl TEXT;
BEGIN
    FOREACH tbl IN ARRAY ARRAY['categories','app_users','products','sale_config','coupons','orders','reviews','wishlist','notifications','chat_messages','menu']
    LOOP
        EXECUTE format(
            'SELECT setval(pg_get_serial_sequence(''public.%I'', ''id''), COALESCE((SELECT MAX(id) FROM public.%I), 1), true)',
            tbl, tbl
        );
    END LOOP;
END;
$$;
